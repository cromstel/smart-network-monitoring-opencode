const D = require('better-sqlite3')
const d = new D('data/dev.db')
const q = (sql) => JSON.stringify(d.prepare(sql).all())
console.log('devices:', q('select device_type, status, count(*) c from devices group by device_type, status order by c desc'))
console.log('bandwidth rows:', q('select count(*) c, min(timestamp) from_, max(timestamp) to_ from bandwidth_metrics'))
console.log('big upload_total sample:', q("select upload_total from bandwidth_metrics where length(upload_total) > 12 limit 3"))
console.log('conn logs:', q('select count(*) c from connection_logs'))
console.log('alerts:', q('select alert_type, device_id from device_alerts'))
d.close()